-- Heart of Wool — migration 004: email notification on new product
--
-- Unlike previous migrations, this one is mostly SETUP STEPS in the
-- Supabase dashboard rather than SQL to run — Database Webhooks are a
-- dashboard-managed feature. Follow the numbered steps below in order.
-- The Edge Function this depends on is in
-- supabase/functions/notify-new-product/index.ts — deploy that FIRST
-- (step 1) before wiring up the webhook (step 2), or the webhook will
-- have nothing to call.

-- ─────────────────────────────────────────────────────────────
-- STEP 1 — Deploy the Edge Function (run from your terminal, in the
-- project root, with the Supabase CLI installed):
--
--   npx supabase login
--   npx supabase link --project-ref <your-project-ref>
--   npx supabase functions deploy notify-new-product
--
-- Your project ref is the subdomain in your Supabase URL, e.g. for
-- https://biutrvnzefzegqigyihm.supabase.co it's "biutrvnzefzegqigyihm".
-- ─────────────────────────────────────────────────────────────

-- ─────────────────────────────────────────────────────────────
-- STEP 2 — Set the function's secrets (also from your terminal):
--
--   npx supabase secrets set RESEND_API_KEY=re_your_key_here
--   npx supabase secrets set NOTIFY_TO_EMAIL=you@example.com
--   npx supabase secrets set NOTIFY_FROM_EMAIL=onboarding@resend.dev
--
-- NOTIFY_TO_EMAIL supports MULTIPLE recipients — separate them with a
-- comma, no spaces needed (they're trimmed automatically either way):
--   npx supabase secrets set NOTIFY_TO_EMAIL=you@example.com,partner@example.com
--
-- NOTIFY_FROM_EMAIL can stay as onboarding@resend.dev (Resend's shared
-- test sender) to start — it works immediately with no domain setup,
-- though emails from it are a little more likely to land in spam.
-- Once you verify your own domain in Resend, switch this to something
-- like notifications@heartofwool.shop for better deliverability.
-- ─────────────────────────────────────────────────────────────

-- ─────────────────────────────────────────────────────────────
-- STEP 3 — Create the Database Webhook in the dashboard:
--
--   Sidebar -> Database -> Webhooks -> Create a new hook
--     Name: notify-new-product
--     Table: products
--     Events: check only "Insert"
--     Type: Supabase Edge Functions
--     Edge Function: notify-new-product
--     HTTP Method: POST
--     HTTP Headers: leave default (Supabase adds auth automatically)
--   Click Create.
-- ─────────────────────────────────────────────────────────────

-- ─────────────────────────────────────────────────────────────
-- STEP 4 — Test it:
--   Add a test product from /admin (or run the insert below directly)
--   and check your email within a minute or two.
--
--   select admin_create_product(
--     'test-notify-01', 'Notification Test Product', 199,
--     'https://picsum.photos/seed/test-notify/600/600',
--     'crochet-charms', 'Just testing the new-product email.', 1
--   );
--
-- Then archive/delete that test product afterward from /admin so it
-- doesn't show up in your real catalog:
--   select admin_set_product_active('test-notify-01', false);
-- ─────────────────────────────────────────────────────────────

-- No SQL needs to run in this file — it exists to document the steps
